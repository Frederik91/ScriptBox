// Builds the package: records the digests of the bundled guest artifacts in
// src/generated/build-info.ts, compiles src to dist and copies the artifacts
// next to it. With --check it only verifies that build-info.ts matches the
// artifacts in the repository, and fails if either is stale.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const repo = join(root, '..');
const wasmDir = join(repo, 'ScriptBox.Wasm');
const artifactFile = 'scriptbox-async.wasm';
const bootstrapFile = 'scriptbox.js';
const artifactPath = join(wasmDir, artifactFile);
const bootstrapPath = join(repo, 'scripts', 'sdk', bootstrapFile);
const buildInfoPath = join(root, 'src', 'generated', 'build-info.ts');

function sha256(path: string): string {
  return createHash('sha256').update(readFileSync(path)).digest('hex');
}

function record(value: unknown): Record<string, unknown> {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) {
    throw new Error('Expected an object.');
  }
  return Object.fromEntries(Object.entries(value));
}

function text(value: unknown, label: string): string {
  if (typeof value !== 'string') {
    throw new Error(`${label} is missing.`);
  }
  return value;
}

function count(value: unknown, label: string): number {
  if (typeof value !== 'number' || !Number.isSafeInteger(value)) {
    throw new Error(`${label} is missing.`);
  }
  return value;
}

const manifest = record(JSON.parse(readFileSync(join(wasmDir, 'artifacts.json'), 'utf8')));
const quickjs = record(manifest['quickjs']);
const artifact = record(record(manifest['artifacts'])[artifactFile]);
const pkg = record(JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')));

const artifactSha = sha256(artifactPath);
if (artifactSha !== text(artifact['sha256'], 'The artifact digest')) {
  throw new Error(`${artifactFile} does not match ScriptBox.Wasm/artifacts.json. Rebuild it with ScriptBox.Wasm/docker-build.sh.`);
}
if (count(artifact['abi'], 'The artifact ABI') !== 2) {
  throw new Error(`${artifactFile} is not an ABI 2 guest.`);
}

const info = {
  packageVersion: text(pkg['version'], 'The package version'),
  quickjs: {
    repository: text(quickjs['repository'], 'The QuickJS repository'),
    commit: text(quickjs['commit'], 'The QuickJS commit'),
  },
  wasiSdk: text(manifest['wasiSdk'], 'The WASI SDK version'),
  artifact: {
    file: artifactFile,
    abi: 2,
    sha256: artifactSha,
    initialMemoryBytes: count(artifact['initialMemoryBytes'], 'The initial memory'),
  },
  bootstrap: {
    file: bootstrapFile,
    sha256: sha256(bootstrapPath),
  },
};

const generated = `// Generated by scripts/build.ts from ScriptBox.Wasm/artifacts.json and the bundled files. Do not edit.
/** The versions and digests this package was built with. The runtime checks the bundled files against them. */
export const buildInfo = Object.freeze(${JSON.stringify(info, null, 2).replace(/"([A-Za-z][A-Za-z0-9]*)":/g, '$1:').replace(/"/g, "'")} as const);
`;

let current = '';
try {
  current = readFileSync(buildInfoPath, 'utf8');
} catch {
  // Written below.
}

if (process.argv.includes('--check')) {
  if (current !== generated) {
    console.error('src/generated/build-info.ts is stale: run npm run build and commit the result.');
    process.exit(1);
  }
  console.log('build-info.ts matches the bundled artifacts.');
  process.exit(0);
}

if (current !== generated) {
  mkdirSync(dirname(buildInfoPath), { recursive: true });
  writeFileSync(buildInfoPath, generated);
}

const dist = join(root, 'dist');
rmSync(dist, { recursive: true, force: true });
execFileSync(process.execPath, [join(root, 'node_modules', 'typescript', 'bin', 'tsc'), '-p', join(root, 'tsconfig.json')], { stdio: 'inherit', cwd: root });
mkdirSync(join(dist, 'assets'), { recursive: true });
copyFileSync(artifactPath, join(dist, 'assets', artifactFile));
copyFileSync(bootstrapPath, join(dist, 'assets', bootstrapFile));
console.log(`Built ${info.packageVersion} with ${artifactFile} ${artifactSha.slice(0, 12)}.`);
